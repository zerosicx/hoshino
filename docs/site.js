/* Hoshino site: the live dictionary demo.
   Loads docs/demo/words.json (generated by scripts/build-site-demo.ts) and
   searches it in the browser. Each row is
   [kanjiForm, reading, firstGloss, jlptLevelOrNull, isCommon]. */

(function () {
  "use strict";

  var form = document.getElementById("demo-form");
  var input = document.getElementById("demo-query");
  var results = document.getElementById("demo-results");
  var status = document.getElementById("demo-status");
  var chips = document.getElementById("demo-chips");
  if (!form || !input || !results || !status) return;

  var MAX_RESULTS = 20;
  var DEBOUNCE_MS = 150;

  /* ---------- Romaji ---------- */

  // Hiragana to Hepburn romaji. Two-character combinations first.
  var DIGRAPHS = {
    "きゃ": "kya", "きゅ": "kyu", "きょ": "kyo",
    "しゃ": "sha", "しゅ": "shu", "しょ": "sho", "しぇ": "she",
    "ちゃ": "cha", "ちゅ": "chu", "ちょ": "cho", "ちぇ": "che",
    "にゃ": "nya", "にゅ": "nyu", "にょ": "nyo",
    "ひゃ": "hya", "ひゅ": "hyu", "ひょ": "hyo",
    "みゃ": "mya", "みゅ": "myu", "みょ": "myo",
    "りゃ": "rya", "りゅ": "ryu", "りょ": "ryo",
    "ぎゃ": "gya", "ぎゅ": "gyu", "ぎょ": "gyo",
    "じゃ": "ja", "じゅ": "ju", "じょ": "jo", "じぇ": "je",
    "ぢゃ": "ja", "ぢゅ": "ju", "ぢょ": "jo",
    "びゃ": "bya", "びゅ": "byu", "びょ": "byo",
    "ぴゃ": "pya", "ぴゅ": "pyu", "ぴょ": "pyo",
    "ふぁ": "fa", "ふぃ": "fi", "ふぇ": "fe", "ふぉ": "fo", "ふゅ": "fyu",
    "てぃ": "ti", "でぃ": "di", "とぅ": "tu", "どぅ": "du", "でゅ": "dyu",
    "うぃ": "wi", "うぇ": "we", "うぉ": "wo",
    "ゔぁ": "va", "ゔぃ": "vi", "ゔぇ": "ve", "ゔぉ": "vo",
    "つぁ": "tsa", "つぃ": "tsi", "つぇ": "tse", "つぉ": "tso",
    "いぇ": "ye"
  };

  var MONOGRAPHS = {
    "あ": "a", "い": "i", "う": "u", "え": "e", "お": "o",
    "か": "ka", "き": "ki", "く": "ku", "け": "ke", "こ": "ko",
    "さ": "sa", "し": "shi", "す": "su", "せ": "se", "そ": "so",
    "た": "ta", "ち": "chi", "つ": "tsu", "て": "te", "と": "to",
    "な": "na", "に": "ni", "ぬ": "nu", "ね": "ne", "の": "no",
    "は": "ha", "ひ": "hi", "ふ": "fu", "へ": "he", "ほ": "ho",
    "ま": "ma", "み": "mi", "む": "mu", "め": "me", "も": "mo",
    "や": "ya", "ゆ": "yu", "よ": "yo",
    "ら": "ra", "り": "ri", "る": "ru", "れ": "re", "ろ": "ro",
    "わ": "wa", "ゐ": "wi", "ゑ": "we", "を": "wo", "ん": "n",
    "が": "ga", "ぎ": "gi", "ぐ": "gu", "げ": "ge", "ご": "go",
    "ざ": "za", "じ": "ji", "ず": "zu", "ぜ": "ze", "ぞ": "zo",
    "だ": "da", "ぢ": "ji", "づ": "zu", "で": "de", "ど": "do",
    "ば": "ba", "び": "bi", "ぶ": "bu", "べ": "be", "ぼ": "bo",
    "ぱ": "pa", "ぴ": "pi", "ぷ": "pu", "ぺ": "pe", "ぽ": "po",
    "ゔ": "vu",
    "ぁ": "a", "ぃ": "i", "ぅ": "u", "ぇ": "e", "ぉ": "o",
    "ゃ": "ya", "ゅ": "yu", "ょ": "yo", "ゎ": "wa",
    "ゕ": "ka", "ゖ": "ke"
  };

  // Katakana (ァ..ヶ) sits 0x60 above hiragana (ぁ..ゖ).
  function foldKana(text) {
    var out = "";
    for (var i = 0; i < text.length; i++) {
      var code = text.charCodeAt(i);
      if (code >= 0x30a1 && code <= 0x30f6) {
        out += String.fromCharCode(code - 0x60);
      } else {
        out += text[i];
      }
    }
    return out;
  }

  function toRomaji(kana) {
    var text = foldKana(kana);
    var out = "";
    var pendingDouble = false;
    var i = 0;
    while (i < text.length) {
      var ch = text[i];
      var pair = text.substr(i, 2);
      var syllable = null;
      var consumed = 1;

      if (ch === "っ") {
        pendingDouble = true;
        i += 1;
        continue;
      }
      if (ch === "ー") {
        // Long vowel mark: repeat the vowel before it.
        var last = out.charAt(out.length - 1);
        if ("aiueo".indexOf(last) !== -1) out += last;
        i += 1;
        continue;
      }
      if (DIGRAPHS[pair]) {
        syllable = DIGRAPHS[pair];
        consumed = 2;
      } else if (MONOGRAPHS[ch]) {
        syllable = MONOGRAPHS[ch];
      }

      if (syllable === null) {
        // Not kana: pass it through (kanji, punctuation, Latin).
        out += ch;
        pendingDouble = false;
        i += 1;
        continue;
      }

      if (pendingDouble) {
        // Small tsu doubles the following consonant; Hepburn writes っち as tchi.
        var first = syllable.charAt(0);
        if (syllable.indexOf("ch") === 0) out += "t";
        else if ("aiueo".indexOf(first) === -1) out += first;
        pendingDouble = false;
      }
      out += syllable;
      i += consumed;
    }
    return out;
  }

  /* ---------- Search ---------- */

  var words = null;
  var romajiCache = null;
  var loadError = false;

  function isLatin(query) {
    return /^[a-z0-9\s'\-]+$/i.test(query);
  }

  function escapeRegExp(s) {
    return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  }

  function jlptRank(level) {
    // N5 first, N1 last, no level after that.
    return level === null ? 6 : 6 - level;
  }

  function search(rawQuery) {
    var query = rawQuery.trim();
    if (!query) return [];
    var matches = [];
    var i;

    if (isLatin(query)) {
      var q = query.toLowerCase().replace(/['\-]/g, "");
      var glossRe = new RegExp("(^|[^a-z])" + escapeRegExp(query.toLowerCase()) + "($|[^a-z])", "i");
      for (i = 0; i < words.length; i++) {
        var w = words[i];
        if (romajiCache[i] === undefined) romajiCache[i] = toRomaji(w[1]).replace(/'/g, "");
        var exact = false;
        if (romajiCache[i].indexOf(q) === 0) {
          exact = romajiCache[i] === q;
        } else if (glossRe.test(w[2])) {
          exact = w[2].toLowerCase() === query.toLowerCase();
        } else {
          continue;
        }
        matches.push({ w: w, exact: exact });
      }
    } else {
      var folded = foldKana(query);
      for (i = 0; i < words.length; i++) {
        var row = words[i];
        var head = row[0];
        var reading = row[1];
        if (head.indexOf(query) === 0 || reading.indexOf(query) === 0 ||
            (folded !== query && (foldKana(head).indexOf(folded) === 0 || foldKana(reading).indexOf(folded) === 0))) {
          matches.push({ w: row, exact: head === query || reading === query });
        }
      }
    }

    matches.sort(function (a, b) {
      if (a.w[4] !== b.w[4]) return b.w[4] - a.w[4];
      var ra = jlptRank(a.w[3]);
      var rb = jlptRank(b.w[3]);
      if (ra !== rb) return ra - rb;
      if (a.exact !== b.exact) return a.exact ? -1 : 1;
      return a.w[0].length - b.w[0].length;
    });

    return matches;
  }

  /* ---------- Rendering ---------- */

  function el(tag, className, text) {
    var node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  }

  function renderRow(w) {
    var head = w[0];
    var reading = w[1];
    var gloss = w[2];
    var level = w[3];
    var common = w[4] === 1;

    var li = document.createElement("li");
    var row = el("div", "result");

    var main = el("div", "result-main");
    var word = el("span", "result-word");
    word.setAttribute("lang", "ja");
    var furi = el("span", "furi", head === reading ? "" : reading);
    furi.setAttribute("aria-hidden", head === reading ? "true" : "false");
    word.appendChild(furi);
    word.appendChild(el("span", "head", head));
    main.appendChild(word);
    main.appendChild(el("span", "result-gloss", gloss));

    var meta = el("div", "result-meta");
    if (level !== null) meta.appendChild(el("span", "pill pill-n" + level, "N" + level));
    if (common) meta.appendChild(el("span", "pill pill-common", "Common"));

    row.appendChild(main);
    if (meta.childNodes.length) row.appendChild(meta);
    li.appendChild(row);
    return li;
  }

  function clear(node) {
    while (node.firstChild) node.removeChild(node.firstChild);
  }

  function setStatus(text) {
    status.textContent = text;
  }

  function showIdle() {
    clear(results);
    if (chips) chips.hidden = false;
    setStatus("");
  }

  function run() {
    var query = input.value.trim();
    if (!query) {
      showIdle();
      return;
    }
    if (chips) chips.hidden = true;
    if (loadError) {
      setStatus("The demo could not load its word list.");
      return;
    }
    if (!words) {
      setStatus("Loading the word list...");
      return;
    }
    var matches = search(query);
    clear(results);
    if (matches.length === 0) {
      setStatus("No matches in the demo list. The app itself knows far more words.");
      return;
    }
    var shown = Math.min(matches.length, MAX_RESULTS);
    setStatus(shown === matches.length
      ? shown + (shown === 1 ? " match" : " matches")
      : "Showing " + shown + " of " + matches.length + " matches");
    var frag = document.createDocumentFragment();
    for (var i = 0; i < shown; i++) frag.appendChild(renderRow(matches[i].w));
    results.appendChild(frag);
  }

  var timer = null;
  function schedule() {
    if (timer) clearTimeout(timer);
    timer = setTimeout(run, DEBOUNCE_MS);
  }

  /* ---------- Wiring ---------- */

  input.addEventListener("input", schedule);
  form.addEventListener("submit", function (event) {
    event.preventDefault();
    if (timer) clearTimeout(timer);
    run();
  });

  if (chips) {
    chips.addEventListener("click", function (event) {
      var target = event.target;
      while (target && target !== chips && !(target.tagName === "BUTTON")) target = target.parentNode;
      if (!target || target === chips) return;
      input.value = target.getAttribute("data-word") || target.textContent;
      input.focus();
      run();
    });
  }

  var url = form.getAttribute("data-words") || "demo/words.json";
  fetch(url)
    .then(function (response) {
      if (!response.ok) throw new Error("HTTP " + response.status);
      return response.json();
    })
    .then(function (data) {
      words = data;
      romajiCache = new Array(words.length);
      if (input.value.trim()) run();
    })
    .catch(function () {
      loadError = true;
      if (input.value.trim()) run();
    });
})();
